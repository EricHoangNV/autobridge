"""UI typed client — OpenAPI → ui/lib/api via openapi-typescript (P1.W7.3)."""

from __future__ import annotations

import json
import pathlib
import subprocess
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[2]
UI_OPENAPI = ROOT / "ui" / "openapi.json"
UI_SCHEMA = ROOT / "ui" / "lib" / "api" / "schema.d.ts"
UI_CLIENT = ROOT / "ui" / "lib" / "api" / "client.ts"


def _live_schema() -> dict:
    from autobridge.control.app import app

    return app.openapi()  # type: ignore[no-untyped-call]


def test_ui_openapi_json_matches_live_schema() -> None:
    assert UI_OPENAPI.exists(), f"{UI_OPENAPI} missing — run make openapi"
    on_disk = json.loads(UI_OPENAPI.read_text(encoding="utf-8"))
    live = _live_schema()
    assert on_disk == live, "ui/openapi.json is stale — run make openapi"
    # Check required endpoints
    required = [
        "/connectors",
        "/connectors/{connector_id}",
        "/connectors/{connector_id}/build",
        "/connectors/{connector_id}/sync",
        "/runs/{run_id}",
        "/runs/{run_id}/events",
        "/drift",
        "/repairs/{repair_id}/approve",
        "/repairs/{repair_id}/reject",
        "/releases/{release_id}/rollback",
        "/demo/inject-fault",
        "/metrics/model-usage",
        "/bench/scorecards",
        "/healthz",
        "/readyz",
    ]
    for p in required:
        assert p in on_disk["paths"], f"missing endpoint {p}"


def test_ui_schema_generated() -> None:
    assert UI_SCHEMA.exists(), f"{UI_SCHEMA} missing — run make openapi"
    text = UI_SCHEMA.read_text(encoding="utf-8")
    assert "auto-generated by openapi-typescript" in text
    assert "export interface paths" in text
    assert "export interface components" in text
    # Must contain key operations
    for op in [
        "list_connectors_connectors_get",
        "create_connector_connectors_post",
        "get_connector_connectors__connector_id__get",
        "trigger_build_connectors__connector_id__build_post",
        "trigger_sync_connectors__connector_id__sync_post",
        "get_run_runs__run_id__get",
        "list_drift_drift_get",
        "get_repair_repairs__repair_id__get",
        "approve_repair_repairs__repair_id__approve_post",
    ]:
        assert op in text, f"missing operation {op} in schema.d.ts"
    # Must contain core schemas
    for s in ["ConnectorOut", "ConnectorDetail", "BuildRequest", "RepairRunOut", "DriftEventOut"]:
        assert s in text, f"missing schema {s}"


def test_ui_client_uses_generated_types() -> None:
    assert UI_CLIENT.exists(), f"{UI_CLIENT} missing"
    text = UI_CLIENT.read_text(encoding="utf-8")
    # Must import from generated schema, not hand-write types
    assert 'from "./schema.d.ts"' in text or 'from "./schema' in text
    assert "createClient<paths>" in text
    assert "openapi-fetch" in text
    # Must re-export key types from components
    for t in ["ConnectorCreate", "ConnectorOut", "BuildRequest", "RepairRunOut"]:
        assert f'components["schemas"]["{t}"]' in text, f"client should re-export {t} from schema"
    # Must cover main endpoints via typed wrappers
    for endpoint in ["/connectors", "/runs/{run_id}", "/repairs/{repair_id}/approve", "/demo/inject-fault"]:
        assert endpoint in text, f"client missing wrapper for {endpoint}"
    # Must not contain hand-written duplicate interfaces for API types
    assert "interface ConnectorOut" not in text, "client must not hand-write ConnectorOut"
    assert "type ConnectorOut =" not in text or 'components["schemas"]["ConnectorOut"]' in text


def test_ui_client_compiles() -> None:
    # tsc --noEmit must pass (client compiles against live schema).
    # `make test` installs ui/node_modules first (ui-deps); a bare pytest run
    # on a fresh clone skips loudly instead of failing on a missing tsc.
    if not (ROOT / "ui" / "node_modules").is_dir():
        pytest.skip("ui/node_modules missing — run make ui-deps (cd ui && npm ci)")
    result = subprocess.run(
        ["npm", "run", "typecheck"],
        cwd=str(ROOT / "ui"),
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, f"ui typecheck failed:\n{result.stdout}\n{result.stderr}"


def test_export_script_check_passes() -> None:
    result = subprocess.run(
        [sys.executable, "scripts/export_openapi.py", "--check"],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        timeout=15,
    )
    assert result.returncode == 0, f"export_openapi --check failed:\n{result.stdout}\n{result.stderr}"
